// clipfmt: a copied GitHub, Jira or Confluence link pastes as a short link in apps that read
// rich text (Slack, Mail, Notes), while terminals still paste the full URL. It writes both
// flavors to the clipboard: HTML <a href="URL">short</a> and the plain URL.
//
// It reads the clipboard only when macOS says (without reading) that it holds a web URL, so
// a copied password is never read. It never logs what is on the clipboard and never uses the
// network. The rules are in ~/.config/clipfmt/rules.tsv (a link to the repo's), the link
// types that are on in ~/.config/clipfmt/enabled; it reloads both when they change.
//
//   clipfmt run              the login agent: watch the clipboard
//   clipfmt test URL         print what URL becomes, with every rule
//   clipfmt status           the rules file and the types that are on
//   clipfmt on|off TYPE      turn a link type on or off (dott does this per type)
//
// Build: bash ~/dotfiles/clipfmt/clipfmt.sh rebuild
import AppKit

let home = FileManager.default.homeDirectoryForCurrentUser.path
let dir = ProcessInfo.processInfo.environment["CLIPFMT_DIR"] ?? home + "/.config/clipfmt"
let rulesPath = dir + "/rules.tsv"
let enabledPath = dir + "/enabled"
let ownType = NSPasteboard.PasteboardType("io.github.jgorodetsky.clipfmt")

// Clipboards to leave alone: password managers mark theirs (nspasteboard.org), rich content
// already has its own links, and clipfmt's own writes.
let skipTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"), .html, .rtf, .rtfd, ownType,
]

struct Rule {
    let type: String
    let re: NSRegularExpression
    let template: String
}

func mtime(_ path: String) -> Date? {
    (try? FileManager.default.attributesOfItem(atPath: path))?[.modificationDate] as? Date
}

/// readRules reads type<TAB>pattern<TAB>short text lines; # starts a comment.
func readRules(_ path: String) throws -> [Rule] {
    let text = try String(contentsOfFile: path, encoding: .utf8)
    var out: [Rule] = []
    for (n, line) in text.components(separatedBy: "\n").enumerated() {
        let l = line.trimmingCharacters(in: .whitespaces)
        if l.isEmpty || l.hasPrefix("#") { continue }
        let f = line.components(separatedBy: "\t")
        guard f.count == 3 else {
            throw NSError(domain: "clipfmt", code: 1, userInfo: [NSLocalizedDescriptionKey: "\(path):\(n + 1): want type<TAB>pattern<TAB>short text"])
        }
        do {
            out.append(Rule(type: f[0], re: try NSRegularExpression(pattern: f[1]), template: f[2]))
        } catch {
            throw NSError(domain: "clipfmt", code: 1, userInfo: [NSLocalizedDescriptionKey: "\(path):\(n + 1): bad pattern: \(error.localizedDescription)"])
        }
    }
    return out
}

func readEnabled(_ path: String) -> Set<String> {
    let text = (try? String(contentsOfFile: path, encoding: .utf8)) ?? ""
    return Set(text.components(separatedBy: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty && !$0.hasPrefix("#") })
}

/// short is what url becomes under the first rule that matches it whole, among the types on.
func short(_ url: String, _ rules: [Rule], on: Set<String>?) -> (type: String, text: String)? {
    let ns = url as NSString
    for r in rules where on == nil || on!.contains(r.type) {
        guard let m = r.re.firstMatch(in: url, range: NSRange(location: 0, length: ns.length)),
              m.range.location == 0, m.range.length == ns.length else { continue }
        var t = r.re.replacementString(for: m, in: url, offset: 0, template: r.template)
        t = t.replacingOccurrences(of: "+", with: " ")
        t = t.removingPercentEncoding ?? t
        return (r.type, t)
    }
    return nil
}

/// oneURL is the clipboard text when it is exactly one https URL, else nil.
func oneURL(_ s: String) -> String? {
    let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
    guard t.hasPrefix("https://"), t.count <= 2048, t.rangeOfCharacter(from: .whitespacesAndNewlines) == nil else { return nil }
    return t
}

func html(_ s: String) -> String {
    s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
        .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
}

func say(_ s: String) { FileHandle.standardError.write((s + "\n").data(using: .utf8)!) }

@MainActor
final class Watcher {
    let pb = NSPasteboard.general
    var seen = NSPasteboard.general.changeCount
    var rules: [Rule] = []
    var on: Set<String> = []
    var rulesTime: Date?
    var onTime: Date?
    var busy = false

    func reload() {
        let rt = mtime(rulesPath), et = mtime(enabledPath)
        if rt != rulesTime {
            rulesTime = rt
            do { rules = try readRules(rulesPath) } catch { say("clipfmt: \(error.localizedDescription)"); rules = [] }
        }
        if et != onTime {
            onTime = et
            on = readEnabled(enabledPath)
        }
    }

    func tick() {
        let count = pb.changeCount
        guard count != seen, !busy else { return }
        seen = count
        reload()
        guard !on.isEmpty, !rules.isEmpty else { return }
        let types = Set(pb.types ?? []) // the kinds of data, not the data
        guard types.contains(.string), types.isDisjoint(with: skipTypes) else { return }
        busy = true
        Task { @MainActor in
            defer { self.busy = false }
            // asks macOS whether it is a web URL without reading it, so nothing else is read
            guard let found = try? await self.pb.detectedPatterns(for: [\.probableWebURL]),
                  found.contains(\.probableWebURL), self.pb.changeCount == count else { return }
            guard let text = self.pb.string(forType: .string), let url = oneURL(text),
                  let s = short(url, self.rules, on: self.on), self.pb.changeCount == count else { return }
            let item = NSPasteboardItem()
            item.setString("<a href=\"\(html(url))\">\(html(s.text))</a>", forType: .html)
            item.setString(url, forType: .string)
            item.setData(Data(), forType: ownType)
            self.pb.clearContents()
            self.pb.writeObjects([item])
            self.seen = self.pb.changeCount
        }
    }
}

func setEnabled(_ type: String, _ want: Bool) throws {
    let types = Set(try readRules(rulesPath).map(\.type))
    guard types.contains(type) else {
        throw NSError(domain: "clipfmt", code: 2, userInfo: [NSLocalizedDescriptionKey: "no type \(type) in \(rulesPath); the types are \(types.sorted().joined(separator: ", "))"])
    }
    var on = readEnabled(enabledPath)
    if want { on.insert(type) } else { on.remove(type) }
    try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
    try (on.sorted().map { $0 + "\n" }.joined()).write(toFile: enabledPath, atomically: true, encoding: .utf8)
}

let args = Array(CommandLine.arguments.dropFirst())
do {
    switch (args.first ?? "", args.count) {
    case ("run", 1):
        MainActor.assumeIsolated {
            let w = Watcher()
            Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { _ in MainActor.assumeIsolated { w.tick() } }
        }
        RunLoop.main.run()
    case ("test", 2):
        let rules = try readRules(rulesPath)
        guard let url = oneURL(args[1]) else { print("unchanged: not one https URL"); exit(0) }
        if let s = short(url, rules, on: nil) { print("\(s.type): \(s.text)") } else { print("unchanged") }
    case ("status", 1):
        let types = try readRules(rulesPath).map(\.type)
        let on = readEnabled(enabledPath)
        print("rules: \(rulesPath)")
        for t in NSOrderedSet(array: types).array as! [String] { print("  \(on.contains(t) ? "on " : "off") \(t)") }
    case ("on", 2), ("off", 2):
        try setEnabled(args[1], args[0] == "on")
        print("\(args[1]) links \(args[0])")
    default:
        say("usage: clipfmt run | test URL | status | on TYPE | off TYPE")
        exit(2)
    }
} catch {
    say("clipfmt: \(error.localizedDescription)")
    exit(1)
}
