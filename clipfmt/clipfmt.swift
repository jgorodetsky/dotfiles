// clipfmt: a copied link pastes as a short link in apps that read rich text (Slack, Mail,
// Notes), while terminals still paste the full URL. It writes both flavors to the clipboard:
// HTML <a href="URL">short</a> and the plain URL.
//
// It reads the clipboard only when macOS says (without reading) that it holds a web URL, so
// a copied password is never read. It never logs what is on the clipboard and never uses the
// network.
//
// The rules: the repo's clipfmt/rules.tsv (--rules or CLIPFMT_RULES; presets and rules for
// every machine) and this Mac's ~/.config/clipfmt/local.tsv, where a line hides the repo's
// lines with its id. The ids that are on: ~/.config/clipfmt/enabled. It reloads all three
// when they change.
//
//   clipfmt run                      the login agent: watch the clipboard
//   clipfmt test URL                 what URL becomes, and under which rule
//   clipfmt parts URL                the link's parts, numbered, to make a rule from
//   clipfmt make URL --vary 1,3 [--any-host]
//                                    a pattern for links like URL, where those parts vary
//   clipfmt groups PATTERN URL       what {1}, {2}... are for URL
//   clipfmt render PATTERN FORMAT URL
//                                    what FORMAT makes of URL
//   clipfmt clip-url                 the copied link, only when the clipboard holds one
//   clipfmt selftest                 every rule's example pastes as its last column
//   any command takes --rules FILE first
//
// Build: bash ~/dotfiles/clipfmt/clipfmt.sh rebuild
import AppKit

let home = FileManager.default.homeDirectoryForCurrentUser.path
let env = ProcessInfo.processInfo.environment
let dir = env["CLIPFMT_DIR"] ?? home + "/.config/clipfmt"
let localPath = dir + "/local.tsv"
let enabledPath = dir + "/enabled"
var repoPath = env["CLIPFMT_RULES"] ?? ""
let ownType = NSPasteboard.PasteboardType("io.github.jgorodetsky.clipfmt")

// Password managers mark what they copy (nspasteboard.org): never read those.
let concealed: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"),
]
// Also left alone by the agent: rich content already has its own links, and clipfmt's own writes.
let skipTypes = concealed.union([.html, .rtf, .rtfd, ownType])

struct Failure: Error, CustomStringConvertible {
    let description: String
    init(_ s: String) { description = s }
}

struct Rule {
    let id: String
    let pattern: String
    let re: NSRegularExpression
    let format: String
    let example: String
    let shows: String
    let local: Bool
}

func mtime(_ path: String) -> Date? {
    (try? FileManager.default.attributesOfItem(atPath: path))?[.modificationDate] as? Date
}

func compile(_ pattern: String) throws -> NSRegularExpression {
    do { return try NSRegularExpression(pattern: pattern) } catch { throw Failure("bad pattern: \(pattern)") }
}

/// readRules reads id<TAB>pattern<TAB>format<TAB>example<TAB>pastes as; # starts a comment.
/// A missing file has no rules.
func readRules(_ path: String, local: Bool) throws -> [Rule] {
    guard !path.isEmpty, FileManager.default.fileExists(atPath: path) else { return [] }
    let text = try String(contentsOfFile: path, encoding: .utf8)
    var out: [Rule] = []
    for (n, line) in text.components(separatedBy: "\n").enumerated() {
        if line.trimmingCharacters(in: .whitespaces).isEmpty || line.hasPrefix("#") { continue }
        let f = line.components(separatedBy: "\t")
        let at = "\(path):\(n + 1)"
        guard f.count == 5 else { throw Failure("\(at): want id<TAB>pattern<TAB>format<TAB>example<TAB>pastes as") }
        guard f[0].range(of: "^[a-z0-9][a-z0-9-]*$", options: .regularExpression) != nil else {
            throw Failure("\(at): the id \(f[0]) takes only a-z, 0-9 and -")
        }
        do {
            out.append(Rule(id: f[0], pattern: f[1], re: try compile(f[1]), format: f[2], example: f[3], shows: f[4], local: local))
        } catch { throw Failure("\(at): \(error)") }
    }
    return out
}

/// rules are this Mac's first, then the repo's whose id this Mac doesn't have.
func loadRules() throws -> [Rule] {
    let mine = try readRules(localPath, local: true)
    let ids = Set(mine.map(\.id))
    return mine + (try readRules(repoPath, local: false)).filter { !ids.contains($0.id) }
}

func readEnabled(_ path: String) -> Set<String> {
    let text = (try? String(contentsOfFile: path, encoding: .utf8)) ?? ""
    return Set(text.components(separatedBy: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty && !$0.hasPrefix("#") })
}

/// whole matches re against all of s, or nil.
func whole(_ re: NSRegularExpression, _ s: String) -> NSTextCheckingResult? {
    let len = (s as NSString).length
    guard let m = re.firstMatch(in: s, range: NSRange(location: 0, length: len)), m.range.location == 0, m.range.length == len else { return nil }
    return m
}

func group(_ m: NSTextCheckingResult, _ n: Int, in s: String) -> String {
    let r = m.range(at: n)
    return r.location == NSNotFound ? "" : (s as NSString).substring(with: r)
}

/// words turns a part's separator into spaces: + when it has one (Confluence), else - and _.
func words(_ raw: String) -> String {
    if raw.contains("+") { return raw.replacingOccurrences(of: "+", with: " ") }
    return raw.replacingOccurrences(of: "-", with: " ").replacingOccurrences(of: "_", with: " ")
}

/// fill puts the groups of a match into format: {N} is group N, decoded; {N:words} the same
/// with its separator as spaces; {host} the link's host, in lower case. Anything else is as typed, $ and \ too.
func fill(_ format: String, _ m: NSTextCheckingResult, in url: String) throws -> String {
    var out = ""
    var rest = Substring(format)
    while let open = rest.firstIndex(of: "{") {
        out += rest[..<open]
        rest = rest[open...]
        guard let close = rest.firstIndex(of: "}") else { break }
        let name = String(rest[rest.index(after: open)..<close])
        rest = rest[rest.index(after: close)...]
        if name == "host" {
            out += URLComponents(string: url)?.host?.lowercased() ?? ""
            continue
        }
        let (num, mode) = name.hasSuffix(":words") ? (String(name.dropLast(6)), "words") : (name, "")
        guard let n = Int(num), n >= 1, String(n) == num else {
            throw Failure("{\(name)}: use {1}, {1:words} or {host}")
        }
        let groups = m.numberOfRanges - 1
        guard n <= groups else {
            throw Failure("no {\(n)}: " + (groups == 0 ? "this pattern has no groups" : groups == 1 ? "only {1} is there" : "{1} to {\(groups)} are there"))
        }
        let raw = group(m, n, in: url)
        let text = mode == "words" ? words(raw) : raw
        out += text.removingPercentEncoding ?? text
    }
    return out + rest
}

/// short is what url becomes under the first rule that matches it whole, among the ids on.
func short(_ url: String, _ rules: [Rule], on: Set<String>?) -> (rule: Rule, text: String)? {
    for r in rules where on == nil || on!.contains(r.id) {
        if let m = whole(r.re, url), let t = try? fill(r.format, m, in: url), !t.isEmpty { return (r, t) }
    }
    return nil
}

/// oneURL is the clipboard text when it is exactly one https URL, else nil.
func oneURL(_ s: String) -> String? {
    let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
    guard t.hasPrefix("https://"), t.count <= 2048, t.rangeOfCharacter(from: .whitespacesAndNewlines) == nil else { return nil }
    return t
}

/// pathParts are a link's path parts as they are in the link, without its query or fragment.
func pathParts(_ url: String) throws -> (host: String, parts: [String]) {
    guard url.hasPrefix("https://"), let c = URLComponents(string: url), let host = c.host, !host.isEmpty else {
        throw Failure("give a whole https link, like https://linear.app/acme/issue/ENG-123/fix-login")
    }
    let port = c.port.map { ":\($0)" } ?? ""
    return (host + port, c.percentEncodedPath.split(separator: "/").map(String.init))
}

/// makePattern is a pattern for links like url: the parts in vary (from 1) can be anything,
/// the others stay as they are. Every part is a group, so {N} is the link's part N.
func makePattern(_ url: String, vary: [Int], anyHost: Bool) throws -> String {
    let (host, parts) = try pathParts(url)
    guard !parts.isEmpty else { throw Failure("this link has no parts after the host") }
    guard !vary.isEmpty else { throw Failure("pick at least one part that changes from link to link") }
    for v in vary where v < 1 || v > parts.count {
        throw Failure("no part \(v): this link has parts 1 to \(parts.count)")
    }
    if anyHost && Set(vary).count == parts.count {
        throw Failure("any host with every part changing would match almost any link; keep a part fixed or the host")
    }
    let h = anyHost ? "[^/?#]+" : "(?i:" + NSRegularExpression.escapedPattern(for: host) + ")"
    let ps = parts.enumerated().map { i, p in
        !vary.contains(i + 1) ? "(" + NSRegularExpression.escapedPattern(for: p) + ")"
            : p.allSatisfy(\.isASCII) && p.allSatisfy(\.isNumber) ? "([0-9]+)" : "([^/?#]+)"
    }
    let pattern = "^https://" + h + "/" + ps.joined(separator: "/") + "(?:[/?#].*)?$"
    guard whole(try compile(pattern), url) != nil else { throw Failure("the pattern doesn't match its own link: \(pattern)") }
    return pattern
}

func html(_ s: String) -> String {
    s.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;")
        .replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;")
}

func say(_ s: String) { FileHandle.standardError.write((s + "\n").data(using: .utf8)!) }

@MainActor
final class Watcher {
    let pb = NSPasteboard.general
    var seen = NSPasteboard.general.changeCount
    var rules: [Rule] = []
    var on: Set<String> = []
    var times: [Date?] = []
    var busy = false

    func reload() {
        let t = [mtime(repoPath), mtime(localPath), mtime(enabledPath)]
        guard t != times else { return }
        times = t
        do { rules = try loadRules() } catch { say("clipfmt: \(error)"); rules = [] }
        on = readEnabled(enabledPath)
    }

    func tick() {
        let count = pb.changeCount
        guard count != seen, !busy else { return }
        seen = count
        reload()
        guard !on.isEmpty, !rules.isEmpty else { return }
        let types = Set(pb.types ?? []) // the kinds of data, not the data
        guard types.contains(.string), types.isDisjoint(with: skipTypes) else { return }
        busy = true
        Task { @MainActor in
            defer { self.busy = false }
            // asks macOS whether it is a web URL without reading it, so nothing else is read
            guard let found = try? await self.pb.detectedPatterns(for: [\.probableWebURL]),
                  found.contains(\.probableWebURL), self.pb.changeCount == count else { return }
            guard let text = self.pb.string(forType: .string), let url = oneURL(text),
                  let s = short(url, self.rules, on: self.on), self.pb.changeCount == count else { return }
            let item = NSPasteboardItem()
            item.setString("<a href=\"\(html(url))\">\(html(s.text))</a>", forType: .html)
            item.setString(url, forType: .string)
            item.setData(Data(), forType: ownType)
            self.pb.clearContents()
            self.pb.writeObjects([item])
            self.seen = self.pb.changeCount
        }
    }
}

var args = Array(CommandLine.arguments.dropFirst())
if args.count >= 2, args[0] == "--rules" {
    repoPath = args[1]
    args.removeFirst(2)
}
let usage = "usage: clipfmt [--rules FILE] run | test URL | parts URL | make URL --vary 1,3 [--any-host] | groups PATTERN URL | render PATTERN FORMAT URL | clip-url | selftest"
do {
    switch (args.first ?? "", args.count) {
    case ("run", 1):
        MainActor.assumeIsolated {
            let w = Watcher()
            Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { _ in MainActor.assumeIsolated { w.tick() } }
        }
        RunLoop.main.run()
    case ("test", 2):
        let rules = try loadRules()
        guard let url = oneURL(args[1]) else { print("unchanged: not one https link"); exit(0) }
        guard let s = short(url, rules, on: nil) else { print("unchanged"); exit(0) }
        print("\(s.rule.id): \(s.text)" + (readEnabled(enabledPath).contains(s.rule.id) ? "" : " (off)"))
    case ("parts", 2):
        let (host, parts) = try pathParts(args[1])
        print("host \(host)")
        for (i, p) in parts.enumerated() { print("\(i + 1) \(p.removingPercentEncoding ?? p)") }
    case ("make", 4), ("make", 5):
        guard args[2] == "--vary", args.count == 4 || args[4] == "--any-host" else { throw Failure(usage) }
        let vary = try args[3].split(separator: ",").map { s -> Int in
            guard let n = Int(s.trimmingCharacters(in: .whitespaces)) else { throw Failure("--vary takes part numbers, like 1,3,4") }
            return n
        }
        print(try makePattern(args[1], vary: vary, anyHost: args.count == 5))
    case ("groups", 3):
        guard let m = whole(try compile(args[1]), args[2]) else { throw Failure("the pattern doesn't match this link") }
        for n in 1..<m.numberOfRanges { print("{\(n)} \(group(m, n, in: args[2]))") }
    case ("render", 4):
        guard let m = whole(try compile(args[1]), args[3]) else { throw Failure("the pattern doesn't match this link") }
        let t = try fill(args[2], m, in: args[3])
        guard !t.isEmpty else { throw Failure("that pastes as nothing") }
        print(t)
    case ("clip-url", 1):
        MainActor.assumeIsolated {
            _ = Task { @MainActor in
                let pb = NSPasteboard.general
                let types = Set(pb.types ?? [])
                guard types.contains(.string), types.isDisjoint(with: concealed),
                      let found = try? await pb.detectedPatterns(for: [\.probableWebURL]), found.contains(\.probableWebURL),
                      let text = pb.string(forType: .string), let url = oneURL(text) else { exit(1) }
                print(url)
                exit(0)
            }
        }
        RunLoop.main.run()
    case ("selftest", 1):
        let rules = try loadRules()
        var bad = 0
        for r in rules {
            let got = short(r.example, rules, on: nil)
            if got?.rule.id != r.id || got?.text != r.shows {
                say("FAIL \(r.id): \(r.example) pastes as \"\(got?.text ?? "unchanged")\" (\(got?.rule.id ?? "no rule")), want \"\(r.shows)\"")
                bad += 1
            }
        }
        if bad > 0 { exit(1) }
        print("every rule's example pastes as it says (\(rules.count) lines)")
    default:
        say(usage)
        exit(2)
    }
} catch {
    say("clipfmt: \(error)")
    exit(1)
}
